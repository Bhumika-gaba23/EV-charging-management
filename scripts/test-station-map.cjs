const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000},geolocation:{latitude:12.9716,longitude:77.5946},permissions:['geolocation']});
    const page=await context.newPage();
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:4173');
    await page.click('[data-vehicle="car"]');
    await page.waitForFunction(()=>document.querySelector('#stationState').options.length===37);
    assert.equal(await page.locator('.station-results').count(),0,'Station-card list must stay removed');
    const hasResults=async()=>assert(parseInt(await page.locator('#stationCount').textContent(),10)>0);
    assert(await page.locator('.leaflet-container').count());
    const mapBox=await page.locator('.station-map-card').boundingBox();
    const searchBox=await page.locator('#stationSearch').boundingBox();
    assert(mapBox.x>searchBox.x && mapBox.height<400,'Map should be a compact upper-right card');
    await page.locator('#expandStationMap').click();
    assert(await page.locator('.station-map-card.expanded').count());
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.station-map-card.expanded').count(),0);
    assert.equal(await page.locator('#stationState option').count(),37);
    await page.locator('#stationState').selectOption('Karnataka');
    await hasResults();
    await page.locator('#stationState').selectOption('all');
    await page.locator('#stationSearch').fill('Kerala');
    await page.locator('#stationSearchForm button[type="submit"]').click();
    await hasResults();
    await page.locator('#stationSearch').fill('Bengaluru');
    await page.locator('#stationSearchForm button[type="submit"]').click();
    await hasResults();
    await page.locator('#stationsInView').check();
    await hasResults();
    await page.locator('#stationsInView').uncheck();
    await page.locator('#locateStations').click();
    assert.equal(await page.locator('#stationState').inputValue(),'all');
    await page.waitForFunction(()=>document.getElementById('stationCount').textContent.includes('nearest first'));
    await hasResults();
    await page.screenshot({path:'.vercel/station-map-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'.vercel/station-map-mobile.png',fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile layout overflows');
    await page.locator('#stationSearch').fill('nonexistentstationxyz');
    await page.locator('#stationSearchForm button[type="submit"]').click();
    assert((await page.locator('#stationCount').textContent()).includes('No matching stations'));
    assert.deepEqual(errors,[]);
    console.log('PASS: compact map, removed cards, state/city search, location, expansion, area filtering, empty results, mobile layout, browser errors');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
